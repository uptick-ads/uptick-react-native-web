#!/bin/bash
# Serves web/index.html, the browser counterpart of the app that installs the Uptick web SDK directly, for the "Web: Serve demo page" task.
# It writes web/config.js from .env.local so the page's inline and popup targets match the app's, then opens the page.
# Runs in the foreground, so the task owns the server and it stops when the task is terminated.
set -euo pipefail
cd "$(dirname "$0")/.."

WEB_PORT="${WEB_PORT:-8090}"

pid="$(lsof -nP -iTCP:"$WEB_PORT" -sTCP:LISTEN -t 2>/dev/null | head -1 || true)"
if [ -n "$pid" ]; then
  echo "Port $WEB_PORT is in use by $(ps -o comm= -p "$pid") (pid $pid); stop it or set WEB_PORT" >&2
  exit 1
fi

if [ -f .env.local ]; then
  set -a
  . ./.env.local
  set +a
  # Same fallbacks as App.js: each target's own integration id, else the shared one.
  python3 - >web/config.js <<'EOF'
import json, os
env = os.environ.get
shared = env("EXPO_PUBLIC_UPTICK_INTEGRATION_ID", "")
config = {
    "host": env("EXPO_PUBLIC_UPTICK_HOST", ""),
    "targets": {
        "inline": {
            "integrationId": env("EXPO_PUBLIC_UPTICK_INLINE_INTEGRATION_ID") or shared,
            "placement": env("EXPO_PUBLIC_UPTICK_INLINE_PLACEMENT", ""),
        },
        "popup": {
            "integrationId": env("EXPO_PUBLIC_UPTICK_POPUP_INTEGRATION_ID") or shared,
            "placement": env("EXPO_PUBLIC_UPTICK_POPUP_PLACEMENT", ""),
        },
    },
}
print("// Generated by tools/web.sh from .env.local; edit .env.local and rerun instead.")
print("window.UPTICK_DEMO_CONFIG = " + json.dumps(config, indent=2) + ";")
EOF
  echo "Wrote web/config.js from .env.local"
else
  rm -f web/config.js
  echo "No .env.local; the page needs ?id=<integration id> in its URL (see README)" >&2
fi

url="http://localhost:$WEB_PORT/"
echo "Inline placement: ${url}?target=inline"
echo "Popup placement:  ${url}?target=popup"
(sleep 1 && open "${url}?target=inline") &
echo "web demo serving on $url"
exec python3 -u -m http.server "$WEB_PORT" --bind 127.0.0.1 --directory web
